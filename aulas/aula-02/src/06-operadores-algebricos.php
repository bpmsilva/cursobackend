<?php
    # Operadores algébricos
    // Adição
    $soma = 10 + 5;
    $soma += 5; // Atribuição com adição
    $soma++; // Incremento

    // Subtração
    $subtracao = 10 - 5;
    $subtracao -= 5; // Atribuição com subtração
    $subtracao--; // Decremento

    // Multiplicação
    $multiplicacao = 10 * 5;
    $multiplicacao *= 5; // Atribuição com multiplicação

    // Divisão
    $divisao = 10 / 5;
    $divisao /= 5; // Atribuição com divisão

    // Exponenciação
    $exponenciacao = 10 ** 5;
    $exponenciacao **= 2; // Atribuição com exponenciação

    // Módulo (ou resto da divisão)
    $modulo = 10 % 5;
